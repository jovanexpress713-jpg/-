const AR_DIACRITICS = /[\u064B-\u0652\u0670\u0640]/g;

/** Split an Arabic string on spaces while keeping the separators. */
function tokens(text: string): string[] {
  return text.split(/(\s+|[·،,:؛.()\-–—/])/g).filter(Boolean);
}

/**
 * Translate an Arabic data string to Urdu using the word map.
 * Returns `null` when fewer than 55% of the Arabic tokens are known, so callers
 * fall back to the English twin instead of emitting mixed gibberish.
 */
export function urduFromArabic(ar: string): string | null {
  if (!ar) return null;
  const clean = ar.replace(AR_DIACRITICS, "");
  const phrase = UR_AR_PHRASES[clean] ?? UR_AR_PHRASES[ar];
  if (phrase) return phrase;

  const parts = tokens(clean);
  let arabicTokens = 0;
  let known = 0;
  const out = parts.map((part) => {
    if (!/[\u0600-\u06FF]/.test(part)) return part;
    arabicTokens += 1;
    const hit = UR_AR_WORDS[part];
    if (hit) {
      known += 1;
      return hit;
    }
    return part;
  });

  if (arabicTokens === 0) return null;
  if (known / arabicTokens < 0.55) return null;
  return out.join("");
}
