function docs(body: Vehicle["body"]): DocState[] {
  const meta: Record<string, string> = {
    "Bill of Lading": "PDF · 240 KB · signed",
    "Commercial Invoice": "PDF · 180 KB · signed",
    "Cargo Insurance": "PDF · 96 KB · valid",
    "Temperature Log": "CSV · 42 KB · live",
    "ADR Certificate": "PDF · 310 KB · valid",
    "Container Manifest": "PDF · 205 KB · sealed",
  };
  return docsFor(body).map((name) => ({
    name,
    meta: meta[name] ?? "PDF · 120 KB",
    state: "idle" as const,
  }));
}

